"""Phase 6 of plan 01: ``portal/examples/`` (kit 04 §2) against the package being tested.

The examples are generated by ``tools/make_examples.py`` calling the package; these tests keep
them honest: same set of cases as the script, template format, every ``expected`` reproduced by
``solve()`` with the portal tolerance (``REL_TOL = 1e-9``, ``golden_lib.py``), the kit coverage,
and V-19 on the examples (D-63 (6)): every m / m.c.a. / L/s list of a success case equals its
own 3-decimal rounding.
"""

from __future__ import annotations

import importlib.util
import json
import math
from typing import Any

import pytest

import mainpipe_transient as mpt
from mainpipe_transient import MainpipeTransientError, solve

from conftest import REPO
from rounding import is_rounded

EXAMPLES_DIR = REPO / "portal" / "examples"
REL_TOL = 1e-9  # backend/tests/golden_lib.py (kit 04 §2)

TEMPLATE_KEYS = {"id", "description", "function", "package_version", "schema_version",
                 "generated_at", "commit", "inputs", "expected"}
ROUNDED_LISTS = (
    "head_valve_m", "head_midpoint_m", "pressure_head_valve_m", "pressure_head_midpoint_m",
    "flow_reservoir_lps", "flow_valve_lps",
    "x_m", "elevation_m", "head_initial_m", "pressure_head_initial_m", "head_max_m",
    "head_min_m", "pressure_head_max_m", "pressure_head_min_m",
    "frame_x_m", "frame_head_m",
)


def _load_tool():
    spec = importlib.util.spec_from_file_location(
        "make_examples", REPO / "tools" / "make_examples.py"
    )
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def _examples() -> dict[str, dict[str, Any]]:
    return {p.stem: json.loads(p.read_text(encoding="utf-8"))
            for p in sorted(EXAMPLES_DIR.glob("*.json"))}


EXAMPLES = _examples()
SUCCESS = {k: v for k, v in EXAMPLES.items() if not v.get("expects_error")}
ERRORS = {k: v for k, v in EXAMPLES.items() if v.get("expects_error")}


def _close(a: Any, b: Any, path: str = "$") -> list[str]:
    """Differences between two JSON values; floats with REL_TOL, everything else exact."""
    if isinstance(a, bool) or isinstance(b, bool) or a is None or b is None:
        return [] if a is b or a == b and type(a) is type(b) else [path]
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        if isinstance(a, int) and isinstance(b, int):
            return [] if a == b else [path]
        return [] if math.isclose(a, b, rel_tol=REL_TOL, abs_tol=0.0) else [path]
    if isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            return [f"{path} (length)"]
        return [d for i, (x, y) in enumerate(zip(a, b)) for d in _close(x, y, f"{path}[{i}]")]
    if isinstance(a, dict) and isinstance(b, dict):
        if a.keys() != b.keys():
            return [f"{path} (keys {sorted(a.keys() ^ b.keys())})"]
        return [d for k in a for d in _close(a[k], b[k], f"{path}.{k}")]
    return [] if a == b else [path]


def test_examples_are_exactly_the_cases_of_the_script():
    tool = _load_tool()
    assert sorted(EXAMPLES) == sorted(c[0] for c in tool.CASES)
    for cid, description, inputs in tool.CASES:
        assert EXAMPLES[cid]["description"] == description
        assert EXAMPLES[cid]["inputs"] == inputs


@pytest.mark.parametrize("cid", sorted(EXAMPLES))
def test_example_format(cid):
    ex = EXAMPLES[cid]
    assert TEMPLATE_KEYS <= ex.keys()
    assert not any(k.startswith("_") for k in ex), "template comments left in the example"
    assert ex["id"] == cid
    assert ex["function"] == "solve"
    assert ex["package_version"] == mpt.__version__
    assert ex["schema_version"] == mpt.SCHEMA_VERSION == "2.0"
    assert len(ex["commit"]) == 40
    assert set(ex["generated_with"]) == {"python", "numpy", "pydantic"}
    if ex.get("expects_error"):
        assert ex["expects_error"] is True
        assert set(ex["expected"]) == {"exception", "http_status"}
        assert isinstance(ex["message"], str) and ex["message"]
    else:
        assert "expects_error" not in ex and "message" not in ex


def test_all_examples_come_from_one_commit():
    assert len({ex["commit"] for ex in EXAMPLES.values()}) == 1


@pytest.mark.parametrize("cid", sorted(SUCCESS))
def test_success_example_is_reproduced_by_solve(cid):
    ex = SUCCESS[cid]
    out = json.loads(json.dumps(solve(json.loads(json.dumps(ex["inputs"])))))
    assert _close(out, ex["expected"]) == []


@pytest.mark.parametrize("cid", sorted(ERRORS))
def test_error_example_is_reproduced_by_solve(cid):
    ex = ERRORS[cid]
    with pytest.raises(MainpipeTransientError) as info:
        solve(json.loads(json.dumps(ex["inputs"])))
    assert type(info.value).__name__ == ex["expected"]["exception"]
    assert info.value.http_status == ex["expected"]["http_status"]
    assert str(info.value) == ex["message"]


@pytest.mark.parametrize("cid", sorted(SUCCESS))
def test_v19_success_example_lists_are_rounded(cid):
    """D-63 (6): the golden cases freeze the rounded values."""
    expected = SUCCESS[cid]["expected"]
    for key in ROUNDED_LISTS:
        value = expected[key]
        if value is None:
            assert key.startswith("frame_")
            continue
        assert is_rounded(value), key


def test_kit_coverage():
    """kit 04 §2: happy path of each mode, every reachable exception, warning/error + checks."""
    statuses = {ex["expected"]["status"] for ex in SUCCESS.values()}
    assert statuses == {"ok", "warning", "error"}
    assert {ex["inputs"].get("geometry", "horizontal") for ex in SUCCESS.values()} == {
        "horizontal", "profile"}
    codes = {c["code"] for ex in SUCCESS.values() for c in ex["expected"]["checks"]}
    assert codes == {"PN_EXCEEDED", "PN_NEAR_LIMIT", "COLUMN_SEPARATION_RISK",
                     "SUBATMOSPHERIC_PRESSURE", "STEADY_NEGATIVE_PRESSURE"}
    assert {ex["expected"]["exception"] for ex in ERRORS.values()} == {
        "MainpipeTransientValidationError"}
    # D-57 (8): only the Excel case carries the player series.
    with_frames = [cid for cid, ex in SUCCESS.items() if ex["expected"]["frame_head_m"] is not None]
    assert with_frames == ["solve-excel-horizontal"]
    excel = SUCCESS["solve-excel-horizontal"]["expected"]
    assert len(excel["frame_time_s"]) == 401 and len(excel["frame_x_m"]) == 21
    assert excel["frame_stride"] == 1


# Phase 8 (0.2.0, amendment F5R-02): the three new 422 examples (U-43, U-44 (5)).
V020_NEW_ERRORS = {
    "error-pn-sobre-maximo": "pn_bar = 100.5 bar está fuera de rango: supera el máximo de 100 "
                             "bar. El timbraje (PN) debe estar entre 1 y 100 bar.",
    "error-pn-bajo-minimo": "pn_bar = 0.5 bar está fuera de rango: es menor que el mínimo de 1 "
                            "bar. El timbraje (PN) debe estar entre 1 y 100 bar.",
    "error-resultado-no-representable": (
        "El resultado del cálculo queda fuera del rango numérico representable: revisa las "
        "magnitudes extremas del nivel del depósito (reservoir_level_m), de las cotas "
        "(pipe_elevation_m o profile_z_m), de la longitud, del diámetro y del caudal inicial. "
        "Con valores de proyecto no se llega a este límite."
    ),
}


def test_v020_fifteen_examples_with_the_three_new_errors():
    assert len(EXAMPLES) == 15
    for cid, message in V020_NEW_ERRORS.items():
        ex = ERRORS[cid]
        assert ex["expected"] == {"exception": "MainpipeTransientValidationError",
                                  "http_status": 422}
        assert ex["message"] == message
        assert ex["inputs"]["include_frames"] is False
    assert ERRORS["error-resultado-no-representable"]["inputs"]["pn_bar"] == 1.0
    assert ERRORS["error-resultado-no-representable"]["inputs"]["reservoir_level_m"] == 1e308
